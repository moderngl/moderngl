import json
import re

lines = ''.join(f'    {json.dumps(line).replace("?", "\\?")}\n' for line in open('moderngl.js').read().splitlines(keepends=True))
block = f'// moderngl.js begin, generated by embed_js.py\nstatic const char webgl_js[] =\n{lines};\n// moderngl.js end\n'
source = open('gl.h').read()
open('gl.h', 'w').write(re.sub(r'// moderngl.js begin.*?// moderngl.js end\n', lambda m: block, source, flags=re.S))
