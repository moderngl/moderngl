import json
import re

source = open('src/gl.h').read()
for name, var in [('moderngl.js', 'webgl_js'), ('webgpu.js', 'webgpu_js')]:
    lines = ''.join(f'    {json.dumps(line).replace("?", "\\?")}\n' for line in open(f'src/{name}').read().splitlines(keepends=True))
    block = f'// {name} begin, generated by embed_js.py\nstatic const char {var}[] =\n{lines};\n// {name} end\n'
    source = re.sub(rf'// {re.escape(name)} begin.*?// {re.escape(name)} end\n', lambda m: block, source, flags=re.S)
open('src/gl.h', 'w').write(source)
